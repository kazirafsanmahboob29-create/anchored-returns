# National electric rate-case figures from the common validated tables.
args <- commandArgs(trailingOnly=TRUE)
out <- if(length(args)) args[1] else 'reports/national-study'
a <- read.csv(file.path(out,'annual.csv'))
a <- a[a$year <= 2024,]
cols <- c('#376b8b','#889ba8')
png(file.path(out,'annual.png'),width=1600,height=850,res=160,bg='white')
par(mfrow=c(1,2),mar=c(4.5,4.2,3,1.2),mgp=c(2.6,.7,0),las=1,family='sans',col.axis='#566a78',col.lab='#334b5a',fg='#c6d2da')
plot(a$year,a$mean_award_bp/100,type='l',lwd=2.2,col=cols[1],xlab='Authorization year',ylab='Mean allowed ROE (%)',ylim=c(8,17),bty='l',main='The longer decline',col.main='#2d3b45',cex.main=1)
abline(h=seq(8,16,2),col='#edf1f4',lwd=.7)
lines(a$year,a$mean_award_bp/100,lwd=2.2,col=cols[1]);points(a$year,a$mean_award_bp/100,pch=16,cex=.35,col=cols[1])
b <- a[a$year>=2010,]
plot(b$year,b$mean_award_bp/100,type='l',lwd=2.2,col=cols[1],xlab='Authorization year',ylab='Percent',ylim=c(0,12),bty='l',main='The recent interest-rate cycle',col.main='#2d3b45',cex.main=1)
abline(h=seq(0,12,2),col='#edf1f4',lwd=.7)
lines(b$year,b$mean_award_bp/100,lwd=2.2,col=cols[1]);lines(b$year,b$mean_treasury_bp/100,lwd=2.2,col=cols[2])
legend('topright',c('Allowed ROE','Treasury at authorization'),col=cols,lwd=2.2,bty='n',cex=.77,text.col='#334b5a')
dev.off()
# Regional comparison: means and coverage are reported together, without inference.
r <- read.csv(file.path(out,'regional_states.csv'))
png(file.path(out,'regional.png'),width=1500,height=800,res=160,bg='white')
par(mar=c(4.5,9,4,9),mgp=c(2.5,.6,0),las=1,family='sans',fg='#c6d2da',col.axis='#566a78',col.lab='#334b5a',xpd=FALSE)
y <- rev(seq_len(nrow(r)))
plot(NA,xlim=c(8.4,10.1),ylim=c(.4,7.4),xlab='Mean reported allowed ROE (%)',ylab='',yaxt='n',xaxt='n',bty='n',main='New England electric observations',col.main='#2f3339',cex.main=1)
abline(v=seq(8.5,10,.5),col='#edf1f4',lwd=.8)
axis(1,at=seq(8.5,10,.5),labels=sprintf('%.1f',seq(8.5,10,.5)),tick=FALSE)
axis(2,at=y,labels=r$state,tick=FALSE,cex.axis=.9)
segments(r$earlier_mean_bp/100,y,r$later_mean_bp/100,y,col='#c4d0d9',lwd=2)
points(r$earlier_mean_bp/100,y,pch=1,col='#8d9faa',cex=1.2,lwd=1.5)
points(r$later_mean_bp/100,y,pch=16,col='#345e78',cex=1.1)
text(10.22,y,paste0('n = ',r$earlier_awards,' / ',r$later_awards),adj=0,cex=.82,col='#617583',xpd=NA)
text(10.22,6.55,'Earlier / later',adj=0,cex=.8,col='#617583',xpd=NA)
text(9.78,y[is.na(r$later_mean_bp)],'Not reported',adj=0,cex=.78,col='#7b858d')
legend('topleft',inset=c(0,0),legend=c('2010-2014','2020-2024'),pch=c(1,16),col=c('#8d9faa','#345e78'),horiz=TRUE,bty='n',cex=.82,text.col='#536875')
dev.off()
